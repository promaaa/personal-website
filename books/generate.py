#!/usr/bin/env python3
"""Generate the bookshelf from books-en.json / books-fr.json, the single source.

Outputs (all committed, nothing runs on the server):
    books/index.html       the English shelf, static HTML (readable without JS)
    books/fr/index.html    the French shelf
    books/books-en.tex     the English reading guide (LaTeX)
    books/books-fr.tex     the French reading guide

Run it through ../generate-pdfs.sh, which also compiles the PDFs with tectonic.
To add a book: add an entry to both JSON files, put its cover in
assets/images/books/ (NN-name.jpg for the PDF, NN-name.webp for the web), run.
"""
import html
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent


def load(lang: str) -> dict:
    return json.loads((ROOT / f"books-{lang}.json").read_text(encoding="utf-8"))


# ---------------------------------------------------------------------------
# HTML
# ---------------------------------------------------------------------------
def h(s: str) -> str:
    """Escape for HTML, turning *emphasis* into <i>."""
    return re.sub(r"\*(.+?)\*", r"<i>\1</i>", html.escape(s, quote=False))


def book_html(b: dict, page: dict, up: str) -> str:
    best = f'<p class="muted">{h(page["best_for"])}: {h(b["best_for"])}</p>' if b.get("best_for") else ""
    words = " ".join([b["title"], b["author"], b["tag"], b["note"], b["spark"]]).lower()
    return f'''          <li class="book" data-words="{html.escape(words)}">
            <img src="{up}assets/images/books/{b["cover"]}.webp" width="160" height="{b["cover_h"]}" loading="lazy" decoding="async" alt="">
            <div>
              <h3>{h(b["title"])}</h3>
              <p class="meta">{h(b["author"])}, {b["year"]}. {h(b["tag"])}</p>
              <p>{h(b["note"])}</p>
              {best}
              <p class="spark">{h(b["spark"])}</p>
            </div>
          </li>'''


