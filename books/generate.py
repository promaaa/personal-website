def tex_cell(b: dict, best_label: str) -> str:
    best = f"{{\\small\\color{{inkmuted}}{esc(best_label)}: {esc(b['best_for'])}}}\\par\\vspace{{1mm}}" if b.get("best_for") else ""
    args = [esc(b["cover"] + ".jpg"), esc(b["title"]), esc(f"{b['author']} ({b['year']})"), esc(b["tag"]), best, esc(b["note"]), esc(b["spark"])]
    return "\\bookentry{" + "}{".join(args) + "}"


def tex(d: dict) -> str:
    g, rows = d["guide"], []
    for s in d["sections"]:
        rows.append("\\multicolumn{2}{@{}p{\\textwidth}@{}}{\\trackheader{" + esc(s["title"]) + "}}\\\\*[2mm]")
        books = s["books"]
        for i in range(0, len(books), 2):
            pair = [tex_cell(b, d["page"]["best_for"]) for b in books[i:i + 2]]
            rows.append(" & ".join(pair + [""] * (2 - len(pair))) + r"\\[3mm]")
    out = PREAMBLE.replace("LANGCODE", d["lang"]).replace("LANG", "french" if d["lang"] == "fr" else "english")
    for k, v in [("TAG", g["masthead_tag"]), ("LOCATION", g["masthead_location"]), ("TITLE", g["masthead_title"]),
                 ("PROLOGUEAUTHOR", g["prologue_author"]), ("PROLOGUE", g["prologue"]),
                 ("COLOPHONLEFT", g["colophon_left"]), ("COLOPHONRIGHT", g["colophon_right"])]:
        out = out.replace(k, esc(v))
    return out.replace("ROWS", "\n".join(rows))


# ---------------------------------------------------------------------------
def main() -> None:
    from subprocess import check_output  # cover heights, so the shelf never shifts while images load
    data = {lang: load(lang) for lang in ("en", "fr")}
    for d in data.values():
        for s in d["sections"]:
            for b in s["books"]:
                f = ROOT.parent / "assets/images/books" / f"{b['cover']}.webp"
                b["cover_h"] = check_output(["identify", "-format", "%h", str(f)]).decode()
    for lang, other in (("en", "fr"), ("fr", "en")):
        d = data[lang]
        out = ROOT / ("index.html" if lang == "en" else "fr/index.html")
        out.parent.mkdir(exist_ok=True)
        out.write_text(shelf_html(d, data[other]), encoding="utf-8")
        (ROOT / f"books-{lang}.tex").write_text(tex(d), encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT.parent)} and books-{lang}.tex ({sum(len(s['books']) for s in d['sections'])} books)")


if __name__ == "__main__":
    main()
