# ---------------------------------------------------------------------------
# LaTeX
# ---------------------------------------------------------------------------
def esc(s: str) -> str:
    s = s.replace("\\", r"\textbackslash{}")
    for a, b in [("{", r"\{"), ("}", r"\}"), ("$", r"\$"), ("&", r"\&"), ("#", r"\#"), ("_", r"\_"),
                 ("%", r"\%"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")]:
        s = s.replace(a, b)
    return re.sub(r"\*(.+?)\*", r"\\textit{\1}", s)


